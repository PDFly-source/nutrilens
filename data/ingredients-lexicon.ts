export function findLexiconMatch(rawIngredientName: string): LexiconEntry | null {
  const clean = rawIngredientName.toLowerCase().replace(/[^a-z0-9\s-]/g, '').trim();
  if (!clean) return null;

  for (const entry of INGREDIENT_LEXICON) {
    for (const pattern of entry.patterns) {
      if (clean === pattern || clean.includes(pattern) || pattern.includes(clean)) {
        return entry;
      }
    }
  }
  return null;
}
